using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace RefinedChemistry.Generators
{
    [Generator]
    public sealed class LocalizableGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var classes = context.SyntaxProvider.ForAttributeWithMetadataName(
                "RefinedChemistry.Attributes.LocalizableAttributes",
                static (node, _) => node is ClassDeclarationSyntax,
                static (attribute, _) =>
                {
                    var declaration = (ClassDeclarationSyntax)attribute.TargetNode;
                    var arguments = attribute.Attributes[0].ConstructorArguments;
                    string prefix = arguments[0].Value + "." + arguments[1].Value + ".";
                    return (
                        Namespace: attribute.TargetSymbol.ContainingNamespace.ToDisplayString(),
                        Name: declaration.Identifier.Text,
                        Modifiers: declaration.Modifiers.ToString(),
                        Prefix: SymbolDisplay.FormatLiteral(prefix, quote: true));
                });

            context.RegisterSourceOutput(classes, static (output, type) =>
            {
                string source = $$"""
                    // <auto-generated/>
                    namespace {{type.Namespace}}
                    {
                        {{type.Modifiers}} class {{type.Name}}
                        {
                            private static string Localize(string property, params object[] args) =>
                                global::RefinedChemistry.LocalizationHelper.Format({{type.Prefix}} + property, args);
                        }
                    }
                    """;
                output.AddSource(type.Namespace + "." + type.Name + ".Localizable.g.cs",
                    SourceText.From(source, Encoding.UTF8));
            });
        }
    }
}
